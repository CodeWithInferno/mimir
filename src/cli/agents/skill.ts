// mimir skill <install | refresh | check | snippet | path>
//
//   install   put the skill folder where an agent finds it: --target claude (its personal skills), --target codex
//             (the shared ~/.agents/skills), or --target <directory>. A link by default, so the skill follows this
//             checkout; --copy for a snapshot. Without --target: every agent whose home directory exists.
//             --agents-md <file> also writes the pointer for agents that read AGENTS.md (between two markers).
//   refresh   regenerate skills/mimir/references/api*.md from the typed reference (what `mimir docs` prints)
//   check     exit 1 when those files are not what refresh would write (for the test suite and for CI)
//   snippet   print the AGENTS.md pointer
//   path      print where the skill folder is
//
// Nothing here is hand-copied API: the reference files are the output of the same code that answers `mimir docs`.
import { cpSync, existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, readlinkSync, rmSync, statSync, symlinkSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { parseFlags, type Parsed } from '../args.ts'
import { parseDts, renderReference, typesPath, type DocIndex } from '../commands/docs.ts'
import { CliError, UsageError, suggest } from '../errors.ts'
import type { Io } from '../io.ts'
import { ROOT, ensureViewer } from '../paths.ts'
import { SKILL_SPEC } from './specs.ts'
import { standalone } from './standalone.ts'
import type { Env } from './types.ts'

export { SKILL_SPEC }
export const SKILL_NAME = 'mimir'
export const SKILL_ACTIONS = ['install', 'refresh', 'check', 'snippet', 'path'] as const
export type SkillAction = (typeof SKILL_ACTIONS)[number]
/** agents whose skill folder this command knows; anything else given to --target is a directory */
export const SKILL_TARGETS = ['claude', 'codex'] as const
export const SNIPPET_BEGIN = '<!-- mimir:begin -->'
export const SNIPPET_END = '<!-- mimir:end -->'
/** prefix of the generated reference files */
export const API_PREFIX = 'api'

export interface SkillOptions {
  action: SkillAction
  targets: string[]
  copy: boolean
  force: boolean
  dryRun: boolean
  agentsMd: string | null
}

export function toSkillOptions(p: Parsed): SkillOptions {
  const action = p.args[0]!
  if (!(SKILL_ACTIONS as readonly string[]).includes(action)) {
    const near = suggest(action, [...SKILL_ACTIONS])
    throw new UsageError(`unknown skill action "${action}"` + (near.length ? `; did you mean ${near.join(', ')}?` : '') + ` (one of: ${SKILL_ACTIONS.join(', ')})`, 'skill')
  }
  const f = p.flags
  const installOnly = ['target', 'copy', 'force', 'dry-run', 'agents-md'].filter((name) => f[name] !== undefined)
  if (action !== 'install' && installOnly.length) throw new UsageError(`--${installOnly[0]} belongs to mimir skill install`, 'skill')
  return {
    action: action as SkillAction, targets: Array.isArray(f.target) ? f.target : [], copy: f.copy === true, force: f.force === true, dryRun: f['dry-run'] === true,
    agentsMd: typeof f['agents-md'] === 'string' ? f['agents-md'] : null,
  }
}

export const skillDir = (root: string = ROOT): string => join(root, 'skills', SKILL_NAME)
export const snippetPath = (root: string = ROOT): string => join(skillDir(root), 'assets', 'AGENTS.snippet.md')

// ── the generated reference ──────────────────────────────────────────────────────────────────────────

/** "parts kit: believable machine parts …" → "parts-kit": the words before the colon, as a file name. */
export function moduleSlug(topic: string): string {
  return topic.split(':')[0]!.trim().toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '')
}

const GENERATED = 'Generated by `mimir skill refresh` from the typed reference (the text `mimir docs` prints). Do not edit: change the declarations and regenerate.'

/** The compact lines of every module, cut out of the one text `mimir docs reference` prints: module → its lines. */
function compactModules(index: DocIndex): Map<string, string[]> {
  const out = new Map<string, string[]>()
  let current: string[] | null = null
  for (const line of renderReference(index).split('\n')) {
    const topic = line.startsWith('# ') ? index.topics.find((t) => t === line.slice(2)) : undefined
    if (topic !== undefined) { current = []; out.set(topic, current) }
    else if (current) current.push(line)
  }
  for (const lines of out.values()) while (lines.length && lines[lines.length - 1] === '') lines.pop()
  return out
}

/** The reference files of the skill: file name → text. */
export function skillReferences(index: DocIndex): Map<string, string> {
  const files = new Map<string, string>()
  const rows: string[] = []
  const modules = compactModules(index)
  for (const topic of index.topics) {
    const slug = moduleSlug(topic)
    const name = `${API_PREFIX}-${slug}.md`
    const body = modules.get(topic) ?? []
    const text = [`# ${topic}`, '', GENERATED, '', '```ts', ...body, '```', ''].join('\n')
    files.set(name, text)
    const callable = [...new Set(index.entries.filter((e) => e.topic === topic && e.parent === null && (e.kind === 'function' || e.kind === 'namespace')).map((e) => e.name))]
    rows.push(`| \`${name}\` | ${(text.length / 1024).toFixed(1)} | ${callable.join(' ') || '(types and members only)'} |`)
  }
  files.set(`${API_PREFIX}.md`, [
    '# API reference: which file to read', '', GENERATED, '',
    'One file per module, one line per declaration (the signature and the first line of its comment). Read the files',
    'of the modules your scene uses; `mimir docs <name>` prints the full comment of one name and where an example uses it.', '',
    '| file | KB | functions |', '|---|---|---|', ...rows, '',
  ].join('\n'))
  return files
}

async function referenceIndex(io: Pick<Io, 'env' | 'log'>): Promise<DocIndex> {
  const file = typesPath(io.env)
  // the reference is generated by the build: bring it up to date first, as `mimir docs` does
  if (!io.env.MIMIR_TYPES) { try { await ensureViewer(io.env, io.log) } catch { /* reported below when the file is missing */ } }
  if (!existsSync(file)) throw new CliError(`the typed reference is missing: ${file} (it is generated by the build: bun scripts/build.ts)`)
  return parseDts(readFileSync(file, 'utf8'))
}

export interface ReferenceDiff { missing: string[]; changed: string[]; stale: string[] }

/** What differs between the reference files on disk and what refresh would write. */
export function diffReferences(dir: string, want: ReadonlyMap<string, string>): ReferenceDiff {
  const have = existsSync(dir) ? readdirSync(dir).filter((n) => new RegExp(`^${API_PREFIX}(-.*)?\\.md$`).test(n)) : []
  const out: ReferenceDiff = { missing: [], changed: [], stale: have.filter((n) => !want.has(n)) }
  for (const [name, text] of want) {
    if (!have.includes(name)) out.missing.push(name)
    else if (readFileSync(join(dir, name), 'utf8') !== text) out.changed.push(name)
  }
  return out
}

// ── install ──────────────────────────────────────────────────────────────────────────────────────────

const home = (env: Env): string => env.HOME ?? env.USERPROFILE ?? homedir()

/** Where an agent looks for personal skills. */
export function targetDir(target: string, env: Env, cwd: string): { name: string; dir: string } {
  if (target === 'claude') return { name: 'claude', dir: join(env.CLAUDE_CONFIG_DIR && env.CLAUDE_CONFIG_DIR !== '' ? env.CLAUDE_CONFIG_DIR : join(home(env), '.claude'), 'skills') }
  if (target === 'codex') return { name: 'codex', dir: join(home(env), '.agents', 'skills') }
  return { name: 'dir', dir: resolve(cwd, target) }
}

/** The agents that are set up on this machine: their home directory exists. */
export function presentTargets(env: Env): string[] {
  const out: string[] = []
  if (existsSync(env.CLAUDE_CONFIG_DIR && env.CLAUDE_CONFIG_DIR !== '' ? env.CLAUDE_CONFIG_DIR : join(home(env), '.claude'))) out.push('claude')
  if (existsSync(join(home(env), '.agents')) || existsSync(env.CODEX_HOME && env.CODEX_HOME !== '' ? env.CODEX_HOME : join(home(env), '.codex'))) out.push('codex')
  return out
}

export interface InstallRow { target: string; path: string; mode: 'link' | 'copy'; status: 'installed' | 'replaced' | 'unchanged' | 'planned' }

function installOne(source: string, target: string, o: SkillOptions, env: Env, cwd: string): InstallRow {
  const { name, dir } = targetDir(target, env, cwd)
  const path = join(dir, SKILL_NAME)
  let mode: InstallRow['mode'] = o.copy ? 'copy' : 'link'
  let exists = false
  let sameLink = false
  try {
    const st = lstatSync(path)
    exists = true
    sameLink = st.isSymbolicLink() && resolve(dirname(path), readlinkSync(path)) === resolve(source)
  } catch { /* nothing there */ }
  if (resolve(path) === resolve(source)) throw new CliError(`${path} is the skill folder itself; name another target`)
  if (exists && sameLink && mode === 'link') return { target: name, path, mode, status: 'unchanged' }
  if (exists && !o.force) throw new CliError(`${path} already exists${sameLink ? ' (a link to this skill)' : ''}; pass --force to replace it`)
  if (o.dryRun) return { target: name, path, mode, status: 'planned' }
  mkdirSync(dir, { recursive: true })
  if (exists) rmSync(path, { recursive: true, force: true })
  if (mode === 'link') {
    try {
      symlinkSync(resolve(source), path, 'junction')
    } catch (e) {
      // no right to make links (Windows without developer mode): a copy does the same job, it just does not follow the checkout
      if ((e as NodeJS.ErrnoException).code !== 'EPERM') throw new CliError(`could not link ${path}: ${(e as Error).message}`)
      mode = 'copy'
    }
  }
  if (mode === 'copy') cpSync(source, path, { recursive: true, dereference: true })
  return { target: name, path, mode, status: exists ? 'replaced' : 'installed' }
}

/** AGENTS.md with the pointer between the two markers: added at the end, or replaced where it already is. */
export function withSnippet(existing: string, snippet: string): string {
  const block = `${SNIPPET_BEGIN}\n${snippet.trim()}\n${SNIPPET_END}`
  const a = existing.indexOf(SNIPPET_BEGIN)
  const b = existing.indexOf(SNIPPET_END)
  if (a >= 0 && b > a) return existing.slice(0, a) + block + existing.slice(b + SNIPPET_END.length)
  return existing.trim() === '' ? block + '\n' : existing.replace(/\n*$/, '\n\n') + block + '\n'
}

export async function skill(o: SkillOptions, io: Io, root: string = ROOT): Promise<number> {
  const source = skillDir(root)
  if (!existsSync(join(source, 'SKILL.md'))) throw new CliError(`the skill is missing: ${join(source, 'SKILL.md')} does not exist in this checkout`)
  const refs = join(source, 'references')

  if (o.action === 'path') {
    io.out(io.json ? JSON.stringify({ path: source }) + '\n' : source + '\n')
    return 0
  }
  if (o.action === 'snippet') {
    const text = readFileSync(snippetPath(root), 'utf8')
    io.out(io.json ? JSON.stringify({ snippet: text }) + '\n' : text.replace(/\n*$/, '\n'))
    return 0
  }
  if (o.action === 'refresh' || o.action === 'check') {
    const want = skillReferences(await referenceIndex(io))
    const diff = diffReferences(refs, want)
    const dirty = diff.missing.length + diff.changed.length + diff.stale.length
    if (o.action === 'refresh' && dirty) {
      mkdirSync(refs, { recursive: true })
      for (const name of [...diff.missing, ...diff.changed]) writeFileSync(join(refs, name), want.get(name)!)
      for (const name of diff.stale) rmSync(join(refs, name), { force: true })
    }
    const result = { ok: o.action === 'refresh' || dirty === 0, files: want.size, ...diff }
    io.out(io.json ? JSON.stringify(result) + '\n'
      : dirty === 0 ? `OK ${want.size} reference files are up to date\n`
        : `${o.action === 'refresh' ? 'WROTE' : 'STALE'} ${[...diff.missing.map((n) => `+${n}`), ...diff.changed.map((n) => `~${n}`), ...diff.stale.map((n) => `-${n}`)].join(' ')}` +
          (o.action === 'check' ? '\nrun: mimir skill refresh\n' : '\n'))
    return result.ok ? 0 : 1
  }

  // install
  const targets = o.targets.length ? o.targets : presentTargets(io.env)
  if (targets.length === 0) throw new CliError(`no agent was found on this machine (no ~/.claude, ~/.agents or ~/.codex); name where the skill should go: mimir skill install --target ${SKILL_TARGETS.join('|')}|<directory>`)
  const rows = targets.map((t) => installOne(source, t, o, io.env, io.cwd))
  let agentsMd: { path: string; status: 'written' | 'unchanged' | 'planned' } | null = null
  if (o.agentsMd !== null) {
    const path = resolve(io.cwd, o.agentsMd)
    if (existsSync(path) && !statSync(path).isFile()) throw new CliError(`--agents-md ${o.agentsMd} is not a file`)
    const before = existsSync(path) ? readFileSync(path, 'utf8') : ''
    const after = withSnippet(before, readFileSync(snippetPath(root), 'utf8'))
    if (after === before) agentsMd = { path, status: 'unchanged' }
    else if (o.dryRun) agentsMd = { path, status: 'planned' }
    else { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, after); agentsMd = { path, status: 'written' } }
  }
  // the skill is text; the work is done by the command line
  const bin = join(root, 'bin', SKILL_NAME)
  const onPath = Bun.which(SKILL_NAME, { PATH: io.env.PATH ?? '' })
  const next: string[] = []
  if (onPath === null) next.push(`put the mimir command on PATH (the skill runs it): link ${bin} into a directory of your PATH`)
  if (rows.some((r) => r.target === 'claude')) next.push(`Claude Code can take the skill and the command together as a plugin instead: claude plugin marketplace add ${root}  then  claude plugin install ${SKILL_NAME}@${SKILL_NAME}`)
  if (rows.some((r) => r.target === 'codex') && agentsMd === null) next.push('agents that read AGENTS.md need a pointer to the skill: mimir skill install --agents-md <your AGENTS.md>, or paste the output of: mimir skill snippet')
  if (io.json) io.out(JSON.stringify({ source, installed: rows, agents_md: agentsMd, mimir_on_path: onPath, next }) + '\n')
  else {
    for (const r of rows) io.out(`${r.status.padEnd(9)} ${r.target.padEnd(6)} ${r.path}  (${r.mode})\n`)
    if (agentsMd) io.out(`${agentsMd.status.padEnd(9)} AGENTS ${agentsMd.path}\n`)
    for (const n of next) io.out(`next: ${n}\n`)
  }
  return 0
}

/** `mimir skill …` from its own arguments (what the command line calls). */
export async function skillCommand(argv: readonly string[], io: Io): Promise<number> {
  return skill(toSkillOptions(parseFlags(SKILL_SPEC, argv)), io)
}

// `bun src/cli/agents/skill.ts <action> …` runs the command on its own (the same code `mimir skill` calls)
if (import.meta.main) await standalone(SKILL_SPEC, skillCommand)
