// bun src/tex/fonts/embed.ts
//
// Writes src/tex/fonts/<group>.ts: the woff2 files of KaTeX's Computer Modern faces (node_modules/katex/dist/fonts,
// SIL Open Font License 1.1) as base64, one module per group of faces, so that every group can be a lazy chunk of
// its own and an exported scene carries exactly the faces its formulas use. Run it again after updating katex;
// tests/unit/tex/fonts.test.ts fails when these modules and the installed package disagree.
import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { FACE_GROUP, FONT_CHUNKS } from '../index.ts'

const root = resolve(import.meta.dir, '../../..')
const fonts = join(root, 'node_modules/katex/dist/fonts')
const version = (JSON.parse(readFileSync(join(root, 'node_modules/katex/package.json'), 'utf8')) as { version: string }).version
const groups = new Map<string, string[]>()
for (const [face, group] of Object.entries(FACE_GROUP)) groups.set(group, [...(groups.get(group) ?? []), face])
for (const [group, faces] of groups) {
  // a group carried by another module's chunk (the stage text faces of src/r2d) is not embedded a second time
  if (FONT_CHUNKS[group] !== 'tex' + group) { console.log(`${group}: in the "${FONT_CHUNKS[group]}" chunk (${faces.join(', ')})`); continue }
  const lines = [
    `// GENERATED by src/tex/fonts/embed.ts from KaTeX ${version} (dist/fonts/*.woff2, SIL Open Font License 1.1). Do not edit.`,
    `/** face → the bytes of its woff2 file, base64 */`,
    'export const FACES: Record<string, string> = {',
    ...faces.map((face) => `  '${face}': '${readFileSync(join(fonts, `KaTeX_${face}.woff2`)).toString('base64')}',`),
    '}',
    '',
  ]
  writeFileSync(join(import.meta.dir, `${group}.ts`), lines.join('\n'))
  console.log(`${group}.ts: ${faces.join(', ')}`)
}
